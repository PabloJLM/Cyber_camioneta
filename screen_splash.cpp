static bool anyButtonPressed() {
  return !digitalRead(PIN_SELECT) ||
         !digitalRead(PIN_UP)     ||
         !digitalRead(PIN_DOWN)   ||
         !digitalRead(PIN_BACK);
}

void screenSplashLoop() {
  static int x = (SCREEN_W - IMG_W) / 2;
  static int y = (SCREEN_H - IMG_H) / 2;
  static float vx = 1.5;//velocidad jsjs
  static float vy = 1.5;
  static int currentPixel = 0;
  static unsigned long lastPixelTime = 0;
  static uint8_t brightness = 50;
  static int8_t direction = 1;
  static unsigned long lastBreatheTime = 0;
  

  x += vx;
  y += vy;
  
  if (x <= 0 || x >= SCREEN_W - IMG_W) vx = -vx;
  if (y <= 0 || y >= SCREEN_H - IMG_H) vy = -vy;
  
  u8g2.clearBuffer();
  u8g2.setBitmapMode(1);
  u8g2.drawXBM(x, y, IMG_W, IMG_H, image_download_bits);
  u8g2.sendBuffer();
  

  if (currentPixel < NUM_PIXELS) {
    neopixelSplashSequence(currentPixel, lastPixelTime);
  } else {
    neopixelBreathe(brightness, direction, lastBreatheTime);
  }
  

  if (anyButtonPressed()) {
    neopixelFadeOut();
    buzzerWelcome();
    currentScreen = SCREEN_MENU;
    delay(200);
  }
}
