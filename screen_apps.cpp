// ========== MAIN LOOP ==========

void screenAppsLoop() {
  // Handle button input
  if (isButtonJustPressed(PIN_BACK)) {
    buzzerClick();
    currentScreen = SCREEN_MENU;
    return;
  }
  
  if (isButtonJustPressed(PIN_UP)) {
    buzzerClick();
    appSelection--;
    if (appSelection < 0) {
      appSelection = TOTAL_APPS - 1;
    }
  }
  
  if (isButtonJustPressed(PIN_DOWN)) {
    buzzerClick();
    appSelection++;
    if (appSelection >= TOTAL_APPS) {
      appSelection = 0;
    }
  }
  
  if (isButtonJustPressed(PIN_SELECT)) {
    buzzerBeep();
    // Acciones para cada app cuando se selecciona
    switch(appSelection) {
      case 0:
        // Wifi Captive Portal
        currentScreen = SCREEN_CAPTIVE;
        break;
      case 1:
        // AP Flood (beacon flooding)
        currentScreen = SCREEN_APFLOOD;
        break;
      case 2:
        // Karma Attack action
        break;
      case 3:
        // Bluetooth Spam - publicidad por BLE advertising
        currentScreen = SCREEN_BTSPAM;
        break;
      case 4:
        // GPS Position action
        break;
      case 5:
        // Wardriving action
        break;
      case 6:
        // Sniffer de paquetes
        currentScreen = SCREEN_SNIFFER;
        break;
    }
  }
  
  // Render screen
  u8g2.clearBuffer();
  
  // Draw current app
  switch(appSelection) {
    case 0:
      drawWifiCaptivePortal();
      break;
    case 1:
      drawAPFlood();
      break;
    case 2:
      drawKarmaAttack();
      break;
    case 3:
      drawBluetoothSpam();
      break;
    case 4:
      drawGPSPosition();
      break;
    case 5:
      drawWardriving();
      break;
    case 6:
      drawSniffer();
      break;
  }

  u8g2.sendBuffer();
}
