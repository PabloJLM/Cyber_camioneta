void screenAppsLoop() {
  if (isButtonJustPressed(PIN_BACK)) {
    buzzerClick();
    currentScreen = SCREEN_MENU;
    return;
  }

  if (isButtonJustPressed(PIN_UP)) {
    buzzerClick();
    appSelection--;
    if (appSelection < 0) {
      appSelection = TOTAL_APPS - 1;
    }
  }

  if (isButtonJustPressed(PIN_DOWN)) {
    buzzerClick();
    appSelection++;
    if (appSelection >= TOTAL_APPS) {
      appSelection = 0;
    }
  }

  if (isButtonJustPressed(PIN_SELECT)) {
    buzzerBeep();
    switch(appSelection) {
      case 0:
        currentScreen = SCREEN_CAPTIVE;
        break;
      case 1:
        currentScreen = SCREEN_APFLOOD;
        break;
      case 2:
        currentScreen = SCREEN_BTSPAM;
        break;
      case 3:
        currentScreen = SCREEN_GPS;
        break;
      case 4:
        break;
      case 5:
        currentScreen = SCREEN_SNIFFER;
        break;
      case 6:
        currentScreen = SCREEN_PCMODE;
        break;
      case 7:
        currentScreen = SCREEN_YMODEM;
        break;
      case 8:
        currentScreen = SCREEN_BLESCAN;
        break;
      case 9:
        currentScreen = SCREEN_MSGPRESET;
        break;
      case 10:
        currentScreen = SCREEN_MESHTERM;
        break;
    }
  }

  u8g2.clearBuffer();

  switch(appSelection) {
    case 0:
      drawWifiCaptivePortal();
      break;
    case 1:
      drawAPFlood();
      break;
    case 2:
      drawBluetoothSpam();
      break;
    case 3:
      drawGPSPosition();
      break;
    case 4:
      drawWardriving();
      break;
    case 5:
      drawSniffer();
      break;
    case 6:
      drawPCMode();
      break;
    case 7:
      drawYModem();
      break;
    case 8:
      drawBleScan();
      break;
    case 9:
      drawMsgPreset();
      break;
    case 10:
      drawMeshTerm();
      break;
  }

  u8g2.sendBuffer();
}
